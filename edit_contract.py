import sys
from docx import Document

SRC = r"C:\Users\ownag\OneDrive\Документы\deepseek-harness\default-workspace\repina_src.docx"
DST = sys.argv[1]

d = Document(SRC)
P = d.paragraphs


def set_run(p, i, text):
    P[p].runs[i].text = text


# ---------- 1. Стороны: наниматель ----------
# p5, r12: "... с одной стороны, и ______ паспорт серия: _____ №___________ выда"
set_run(5, 12, ", с одной стороны, и Самариева Ирина Петровна, паспорт серия: 03 15 №014286 выда")
# p5, r13: "н   ______" -> выдан + кем выдан
set_run(5, 13, "н Отделом УФМС России по Краснодарскому краю в городе-курорте Анапа, код подразделения 230-020")

# p6, r0: дата выдачи
set_run(6, 0, "«10» октября 2014 г., зарегистрирован")
# p6, r1: "_" -> "ная"
set_run(6, 1, "ная")
# p6, r2: адрес + тел + именуем___
set_run(6, 2, " по адресу: Краснодарский край, ст. Гостагаевская, ул. Урожайная, д. 7\u00a0«А»; тел.: __________________ именуемая в дальнейшем ")

# ---------- 2. Плата за наём: 27 000 ----------
# p26: "... составляет 30000 (тридцать две тысячи) рублей в месяц."
set_run(26, 3, "т 27")
set_run(26, 4, "0")
set_run(26, 5, "00 ")
set_run(26, 7, "двадцать семь тысяч")

# p30: гарантийный залог 30000 (тридцати двух тысяч) -> 27000 (двадцать семь тысяч)
set_run(30, 9, "2")
set_run(30, 10, "7")
set_run(30, 11, "000 (двадцать семь тысяч) рублей")

# ---------- 3. Подписи ----------
set_run(53, 1, ": Шулика Григорий Андреевич  ________________________________________")
set_run(57, 1, ": Самариева Ирина Петровна  ________________________________________")

# ---------- 4. Акт передачи ----------
set_run(66, 4, "  в  дальнейшем  НАЙМОДАТЕЛЬ, с одной стороны, и Самариева Ирина Петровна, именуемая в дальнейшем НАНИМАТЕЛЬ, с другой стороны, заключили настоящий Акт о нижеследующем:")

d.save(DST)
print("saved", DST)
